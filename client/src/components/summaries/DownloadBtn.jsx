import React from 'react';
import { Button } from '../ui/Button';
import { Download } from 'lucide-react';

const DownloadBtn = ({ title, summary, fileName, createdAt }) => {
  const handleDownload = () => {
    const summaryContent = `# ${title}
Generated Summary
Generated on: ${new Date(createdAt).toLocaleDateString()}
    
${summary}
    
Original File: ${fileName}
Generated by Sommaire - AI PDF Summarizer
`;

    const blob = new Blob([summaryContent], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);

    const link = document.createElement('a');
    link.href = url;
    link.download = `Summary-${title.replace(/[^a-zA-Z0-9_-]/gi, '_')}.txt`;
    document.body.appendChild(link);
    link.click();

    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <Button
      variant="outline"
      className="bg-rose-100 hover:bg-rose-200 border-rose-200 text-rose-700 flex items-center gap-2 rounded-full px-4"
      onClick={handleDownload}
    >
      <Download className="h-4 w-4 text-rose-600" />
      <span className="text-sm font-medium">Download Summary</span>
    </Button>
  );
};

export default DownloadBtn;
